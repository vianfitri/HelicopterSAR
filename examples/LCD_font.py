# ============================================================
# TFT DISPLAY
# ============================================================

class TFTDisplay(wx.Panel):

    def __init__(self, parent):

        super().__init__(
            parent,
            size=(WIDTH, HEIGHT)
        )

        self.SetBackgroundStyle(
            wx.BG_STYLE_PAINT
        )

        # Framebuffer
        self.bitmap = wx.Bitmap(
            WIDTH,
            HEIGHT,
            depth=32
        )

        self.clear(BLACK)

        self.Bind(
            wx.EVT_PAINT,
            self.on_paint
        )

    # ========================================================
    # FRAMEBUFFER
    # ========================================================

    def clear(self, color):

        dc = wx.MemoryDC()
        dc.SelectObject(self.bitmap)

        dc.SetBackground(
            wx.Brush(wx.Colour(*color))
        )

        dc.Clear()

        dc.SelectObject(wx.NullBitmap)

    # ========================================================
    # DRAW ONE TFT PIXEL
    # ========================================================

    def draw_pixel(self, x, y, color):

        if not (
            0 <= x < WIDTH and
            0 <= y < HEIGHT
        ):
            return

        dc = wx.MemoryDC()
        dc.SelectObject(self.bitmap)

        dc.SetPen(
            wx.Pen(wx.Colour(*color))
        )

        dc.DrawPoint(x, y)

        dc.SelectObject(wx.NullBitmap)

    # ========================================================
    # DRAW BITMAP FONT
    # ========================================================

    def draw_char_5x7(
        self,
        char,
        x,
        y,
        color=WHITE,
        scale=1
    ):

        char = char.upper()

        glyph = FONT_5X7.get(
            char,
            FONT_5X7[" "]
        )

        for row, bits in enumerate(glyph):

            for col in range(5):

                # Periksa bit dari kiri ke kanan
                if bits & (1 << (4 - col)):

                    # scale = 1:
                    #
                    # 1 font pixel
                    # =
                    # 1 TFT pixel
                    #
                    #
                    # scale = 2:
                    #
                    # 1 font pixel
                    # =
                    # 2x2 TFT pixels

                    for sy in range(scale):

                        for sx in range(scale):

                            self.draw_pixel(
                                x + col * scale + sx,
                                y + row * scale + sy,
                                color
                            )

    # ========================================================
    # DRAW STRING
    # ========================================================

    def draw_text_5x7(
        self,
        text,
        x,
        y,
        color=WHITE,
        scale=1
    ):

        cursor_x = x

        for char in text:

            self.draw_char_5x7(
                char,
                cursor_x,
                y,
                color,
                scale
            )

            # 5 pixel glyph
            # + 1 pixel spacing

            cursor_x += 6 * scale

    # ========================================================
    # PAINT
    # ========================================================

    def on_paint(self, event):

        dc = wx.PaintDC(self)

        dc.DrawBitmap(
            self.bitmap,
            0,
            0,
            False
        )


# ============================================================
# MAIN WINDOW
# ============================================================

class MainFrame(wx.Frame):

    def __init__(self):

        super().__init__(
            None,
            title="TFT 160x80 Bitmap Font"
        )

        self.SetClientSize(
            WIDTH,
            HEIGHT
        )

        self.tft = TFTDisplay(self)

        # ----------------------------------------------------
        # Contoh penggunaan
        # ----------------------------------------------------

        self.tft.draw_text_5x7(
            "T12 SOLDER",
            5,
            5,
            WHITE,
            scale=1
        )

        self.tft.draw_text_5x7(
            "350",
            5,
            20,
            ORANGE,
            scale=3
        )

        self.tft.draw_text_5x7(
            "READY",
            100,
            68,
            GREEN,
            scale=1
        )

        self.tft.Refresh()

        self.Centre()


# ============================================================
# APPLICATION
# ============================================================

class App(wx.App):

    def OnInit(self):

        frame = MainFrame()

        frame.Show()

        return True


# ============================================================
